"""Console and JSON reporting utilities for security alerts."""

import json
from dataclasses import asdict
from pathlib import Path

from security.log_sentinel.models import SecurityAlert

SEVERITY_COLORS = {
    "CRITICAL": "\033[1;31m",  # Bold Red
    "HIGH": "\033[1;33m",      # Bold Yellow
    "MEDIUM": "\033[1;36m",    # Bold Cyan
}
RESET = "\033[0m"


def print_console_report(alerts: list[SecurityAlert], log_path: str) -> None:
    """Prints a formatted summary of detected security alerts to stdout.

    Args:
        alerts: List of SecurityAlert instances generated by the pipeline.
        log_path: Path of the analyzed log file for display context.
    """
    print(f"\n[*] Log Sentinel Analysis -> {log_path}")
    if not alerts:
        print("\033[1;32m[+] No anomalies detected above threshold.\033[0m\n")
        return

    print(f"\033[1;31m[!] {len(alerts)} security alert(s) triggered:\033[0m\n")
    for alert in alerts:
        color = SEVERITY_COLORS.get(alert.severity, "")
        users_str = ", ".join(alert.targeted_users)
        print(f"  {color}[{alert.severity}] {alert.rule_name}{RESET}")
        print(f"    ├─ Source IP      : {alert.source_ip}")
        print(f"    ├─ Failed Attempts: {alert.attempt_count}")
        print(f"    ├─ Targeted Users : {users_str}")
        print(f"    └─ Detected At    : {alert.detected_at}\n")


def export_json_report(alerts: list[SecurityAlert], output_path: str | Path) -> None:
    """Exports detected alerts as a clean, ANSI-free JSON report.

    Args:
        alerts: List of SecurityAlert instances to serialize.
        output_path: Destination file path for the JSON output.
    """
    destination = Path(output_path)
    destination.parent.mkdir(parents=True, exist_ok=True)

    payload = {
        "tool": "log_sentinel",
        "total_alerts": len(alerts),
        "alerts": [asdict(alert) for alert in alerts],
    }

    with destination.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2)

    print(f"[+] JSON report saved to: {destination}")